"""Generate a shared stream curve for terrain, water and offline authoring."""
import json, math, pathlib, re
root=pathlib.Path(__file__).resolve().parents[2]
if (root/'assets/environments/snow/smooth_polar_stream.gdshaderinc').exists():
 raise SystemExit('Shared stream already exists; refusing repeated shader replacement.')
old=json.loads((root/'tools/authoring/polar_waterways_layout.json').read_text())
zs=[-170,-145,-120,-90,-65,-40]
rows=[]
for i in range(17):
 t=i/16; z=-170+130*t
 k=min(4,next((j for j in range(5) if z<=zs[j+1]),4))
 u=(z-zs[k])/(zs[k+1]-zs[k])
 level=old['stream_levels'][k]*(1-u)+old['stream_levels'][k+1]*u
 rows.append([-215+27*t+4*math.sin(t*math.tau),z,level,3.4+.75*math.sin(t*math.tau+.5)+.35*math.sin(t*math.pi*5)])
dest=root/'assets/environments/snow/smooth_stream_layout.json'
dest.write_text(json.dumps(rows,indent=2))
points=','.join('vec4('+','.join(f'{v:.7f}' for v in row)+')' for row in rows)
inc='''// Generated by tools/authoring/smooth_polar_stream.py. xy=center, z=water height, w=half width.
vec3 polar_stream_sample(vec2 p) {
 vec4 points[17]=vec4[](%s);
 vec3 result=vec3(10000.0,0.0,0.0);
 for(int i=0;i<16;i++) {
  vec4 a=points[i];vec4 b=points[i+1];
  float t=clamp(dot(p-a.xy,b.xy-a.xy)/dot(b.xy-a.xy,b.xy-a.xy),0.0,1.0);
  float d=length(p-mix(a.xy,b.xy,t));
  if(d<result.x)result=vec3(d,mix(a.z,b.z,t),mix(a.w,b.w,t));
 }
 return result;
}
'''%points
(root/'assets/environments/snow/smooth_polar_stream.gdshaderinc').write_text(inc)
water=root/'assets/environments/snow/shallow_polar_water.gdshader'
text=water.read_text()
text=re.sub(r'float stream_distance\(vec2 p\) \{.*?\n\}', '#include "res://assets/environments/snow/smooth_polar_stream.gdshaderinc"\nfloat stream_distance(vec2 p) { vec3 s=polar_stream_sample(p);return s.x-s.z;\n}',text,flags=re.S)
water.write_text(text.replace('#include "res://assets/environments/snow/smooth_polar_stream.gdshaderinc"',inc))
terrain=root/'assets/environments/snow/terrain_cliff_cutout.gdshader'
text=terrain.read_text()
text=text.replace('void extra_polar_surfaces(', '#include "res://assets/environments/snow/smooth_polar_stream.gdshaderinc"\nvoid extra_polar_surfaces(')
start=text.index(' float nearest=10000.0;float level=0.0;',text.index('void extra_polar_surfaces'))
end=text.index(' float area=1.0-smoothstep(6.0,12.0,nearest);',start)
text=text[:start]+' vec3 stream=polar_stream_sample(p.xz);float nearest=stream.x;float level=stream.y;\n'+text[end:]
text=text.replace('float frost_area=1.0-smoothstep(6.0,16.0,nearest+bank_variation);','float frost_area=1.0-smoothstep(stream.z+2.6,stream.z+12.6,nearest+bank_variation);')
terrain.write_text(text.replace('#include "res://assets/environments/snow/smooth_polar_stream.gdshaderinc"',inc))
print('Shared stream: 17 cross-sections; half-width',min(r[3] for r in rows),max(r[3] for r in rows))
